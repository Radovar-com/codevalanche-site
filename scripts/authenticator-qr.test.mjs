import test from 'node:test';
import assert from 'node:assert/strict';
import {authenticatorQrSource,AUTHENTICATOR_QR_MAX_LENGTH} from '../src/account/authenticatorQr.js';
test('provider SVG data is encoded without losing black QR modules at a hash or percent sign',()=>{
 const svg='<svg xmlns="http://www.w3.org/2000/svg"><path fill="#000" data-note="100%" d="M1 1h8v8H1z"/></svg>';
 for(const payload of [svg,encodeURIComponent(svg)]){
  const source=authenticatorQrSource('data:image/svg+xml;utf-8,'+payload);
  assert.ok(source.startsWith('data:image/svg+xml;charset=utf-8,'));assert.equal(decodeURIComponent(source.split(',').slice(1).join(',')),svg);
 }
});
test('the QR image never uses a remote service, an executable document, malformed encoding or oversized data',()=>{
 for(const source of [null,'','https://qr.example.test/?secret=SYNTHETIC','javascript:alert(1)','data:text/html,<svg/>','data:image/svg+xml;utf-8,%zz','data:image/svg+xml;utf-8,not-an-svg','data:image/svg+xml;utf-8,<svg>'+ 'x'.repeat(AUTHENTICATOR_QR_MAX_LENGTH)])assert.equal(authenticatorQrSource(source),'');
});

// The shape Supabase Auth actually returns (SVGo + goqrsvg, level H, 3 px blocks, one <rect> per module,
// black and white), prefixed by auth-js. A QR for a real otpauth URI is version 12-14: 65-73 modules wide.
function providerShapedQr(width){
 const rects=[];for(let x=0;x<width;x++)for(let y=0;y<width;y++)rects.push(`<rect x="${12+x*3}" y="${12+y*3}" width="3" height="3" style="fill:${(x*y+x)%3?'white':'black'};stroke:none" />`);
 const size=24+width*3;
 return `data:image/svg+xml;utf-8,<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg width="${size}" height="${size}"\n     xmlns="http://www.w3.org/2000/svg"\n     xmlns:xlink="http://www.w3.org/1999/xlink">\n${rects.join('\n')}\n</svg>\n`;
}
test('a full-size QR as Supabase Auth draws it is shown, not refused for its size',()=>{
 for(const width of [65,73,97]){
  const raw=providerShapedQr(width),source=authenticatorQrSource(raw);
  assert.ok(raw.length>200000||width<73,`width ${width} is realistic (${raw.length} chars)`);
  assert.ok(source.startsWith('data:image/svg+xml;charset=utf-8,'),`width ${width} (${raw.length} chars) must render`);
  assert.equal(decodeURIComponent(source.slice(source.indexOf(',')+1)),raw.slice(raw.indexOf(',')+1));
 }
});
